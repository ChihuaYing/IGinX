package cn.edu.tsinghua.iginx.engine.physical.storage.descriptor;

import cn.edu.tsinghua.iginx.engine.physical.storage.IStorage;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Declares the {@link StorageDriverDescriptor} of a driver, on the class implementing {@link
 * IStorage}. The descriptor needs a public no-arg constructor. Drivers without it use {@link
 * StorageDriverDescriptor#DEFAULT}.
 */
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE)
public @interface DriverDescriptor {
  Class<? extends StorageDriverDescriptor> value();
}
